// src/lib/e2eeReset.ts
//
// Диалог замены ключа шифрования.
//
// Приватный ключ существует только на устройстве, поэтому после переустановки
// приложения или очистки данных он потерян, а в profiles.public_key остаётся
// ключ старой установки. Отправка в таком состоянии блокируется, и выйти из
// него из интерфейса было нельзя: пользователь видел ошибку и не мог ничего
// сделать.
//
// Молча перезаписывать публичный ключ нельзя — старая переписка после этого
// не расшифруется ни на одном устройстве. Поэтому спрашиваем явно и только
// после подтверждения заменяем ключ и повторяем действие (отправку), которое
// пользователь пытался выполнить.

import { appAlert } from './alert';
import { resetIdentity } from './e2ee';

export function offerKeyReset(
  userId: string,
  reason: string,
  retry: () => void | Promise<void>
): void {
  appAlert.alert(
    'Заменить ключ шифрования?',
    `${reason}\n\nНовый ключ позволит снова отправлять сообщения. Старые сообщения останутся зашифрованными — прочитать их на этом устройстве не получится.`,
    [
      { text: 'Отмена', style: 'cancel' },
      {
        text: 'Заменить ключ',
        style: 'destructive',
        onPress: async () => {
          try {
            await resetIdentity(userId);
            await retry();
          } catch (e: any) {
            appAlert.alert('Не удалось заменить ключ', e?.message ?? String(e));
          }
        },
      },
    ]
  );
}
