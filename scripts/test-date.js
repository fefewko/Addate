// Проверка расчёта возраста и разбора даты: scripts/test-date.js
//
// Зачем этот файл в репозитории:
//
// Логика даты рождения решает, пустят ли в приложение несовершеннолетнего.
// Ошибка в ней — не «некрасивый текст», а дыра в возрастном ограничении,
// поэтому её нужно проверять, а не полагаться на внимательность.
//
// Почему не jest: ради сорока строк логики поднимать тестовый раннер в
// проекте, где его больше нигде нет, незачем. Node 24 умеет запускать
// TypeScript напрямую, поэтому проверка запускается обычным node и требует
// только совпадения версии Node.
//
// Про «текущую дату»: проверки возраста подставляют сегодняшний день явно,
// иначе набор ожиданий пришлось бы переписывать каждый день, а через год
// он молча проверял бы уже не то. Порог 18 лет привязан к этой дате, и
// набор ниже построен так, чтобы пережить смену года без правок.
//
// Запуск: npm run test:date

const {
  toDate,
  ageFrom,
  partsToIso,
  isoToParts,
  validateBirthDateParts,
  MIN_AGE_YEARS,
} = require('../src/lib/date.ts');

let failed = 0;
let total = 0;

function check(label, actual, expected) {
  total++;
  const ok = JSON.stringify(actual) === JSON.stringify(expected);
  if (!ok) {
    failed++;
    console.log(`  ✗ ${label}\n      получено: ${JSON.stringify(actual)}\n      ожидалось: ${JSON.stringify(expected)}`);
  }
  return ok;
}

function parts(day, month, year) {
  return { day: String(day).padStart(2, '0'), month: String(month).padStart(2, '0'), year: String(year) };
}

function group(name) {
  console.log(`\n${name}`);
}

// ---------------------------------------------------------------------------
// 1. Порог совершеннолетия относительно явно заданной даты
// ---------------------------------------------------------------------------
// Главное здесь — три граничных случая: 18 лет исполнялось вчера, сегодня и
// завтра. Ошибка на любом из них означает, что подросток либо не сможет
// зарегистрироваться, либо зарегистрируется.
const referenceDay = new Date(2026, 8, 27); // 27.09.2026

group('Порог 18 лет (относительно 27.09.2026)');
[
  [2008, 9, 26, 18, 'вчера исполнилось 18'],
  [2008, 9, 27, 18, 'сегодня исполняется 18'],
  [2008, 9, 28, 17, 'завтра исполнится 18, ещё нет'],
  [2008, 10, 1, 17, 'день рождения дальше в этом году'],
  [2009, 1, 15, 17, '17 полных лет'],
  [2009, 12, 31, 16, '16 полных лет'],
  [1990, 5, 15, 36, 'взрослый'],
  [1926, 9, 27, 100, 'ровно 100'],
  [1926, 9, 28, 99, '99, день рождения завтра'],
].forEach(([y, m, d, expected, label]) => {
  const date = toDate(parts(d, m, y));
  const actual = date ? ageFrom(date, referenceDay) : null;
  check(`${y}-${m}-${d}: ${label}`, actual, expected);
});

// ---------------------------------------------------------------------------
// 2. Календарная корректность
// ---------------------------------------------------------------------------
// Здесь важно, что проверка не доверяет разбору ISO-строк движком: движки
// расходятся в том, считают ли они 31 февраля датой или нет.
group('Календарные даты');
[
  [2001, 2, 31, null, '31 февраля не бывает'],
  [2001, 13, 1, null, 'месяца 13 не бывает'],
  [2001, 0, 10, null, 'месяца 0 не бывает'],
  [2001, 1, 0, null, 'дня 0 не бывает'],
  [2001, 1, 32, null, 'дня 32 не бывает'],
  [2001, 4, 31, null, 'апреля 31 дня'],
  [2025, 2, 29, null, '29 февраля в невысокосном году'],
  [2024, 2, 29, new Date(2024, 1, 29).getTime(), '29 февраля в високосном году бывает'],
  [2000, 2, 29, new Date(2000, 1, 29).getTime(), '2000 тоже високосный (делится на 400)'],
  [1900, 2, 29, null, '1900 не високосный (делится на 100, но не на 400)'],
].forEach(([y, m, d, expected, label]) => {
  const date = toDate(parts(d, m, y));
  const actual = date ? date.getTime() : null;
  check(`${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}: ${label}`, actual, expected);
});

// ---------------------------------------------------------------------------
// 3. Округление возраста по календарю, а не долей года
// ---------------------------------------------------------------------------
// Считать возраст как (now - birth) / 365.25 нельзя: человек, которому 18
// исполнится через месяц, получился бы «18-летним». Именно из-за этой ошибки
// 18-летние подростки проходили бы проверку.
group('Округление возраста');
[
  [new Date(2008, 1, 29), new Date(2026, 8, 27), 18, 'день рождения в этом году уже был'],
  [new Date(2008, 1, 29), new Date(2026, 0, 15), 17, 'день рождения в этом году ещё впереди'],
  [new Date(2008, 1, 29), new Date(2026, 1, 28), 17, 'за день до восемнадцатилетия'],
  [new Date(2008, 1, 29), new Date(2026, 1, 29), 18, 'в день восемнадцатилетия'],
  [new Date(2008, 11, 31), new Date(2026, 11, 31), 18, 'день рождения в день рождения'],
].forEach(([birthDate, today, expected, label]) => {
  check(label, ageFrom(birthDate, today), expected);
});

// ---------------------------------------------------------------------------
// 4. Согласованность validateBirthDateParts с разбором и возрастом
// ---------------------------------------------------------------------------
// Здесь сегодняшняя дата не подменяется: проверяется не «какой сейчас
// возраст», а одно свойство — что validate отвечает «можно тогда и только
// тогда, когда разбор даты удался и возраст попадает в границы». Эталон
// считается независимо, через toDate и ageFrom, поэтому такая проверка не
// превращается в «сравнение функции с самой собой».
group('validateBirthDateParts согласована с разбором и возрастом');
[
  [1990, 5, 15, 'взрослый'],
  [2010, 5, 15, 'ребёнок'],
  [2001, 2, 31, 'несуществующая дата'],
  [1920, 1, 1, 'больше верхней границы'],
  [1880, 1, 1, 'заведомо неправдоподобный год'],
].forEach(([y, m, d, label]) => {
  const p = parts(d, m, y);
  const date = toDate(p);
  const age = date ? ageFrom(date) : null;
  const expectedAllowed = age !== null && age >= MIN_AGE_YEARS && age <= 100;
  check(`${y}-${m}-${d}: ${label}`, validateBirthDateParts(p) === null, expectedAllowed);
});

check('пустая дата отклоняется', validateBirthDateParts({ day: '', month: '', year: '' }) !== null, true);

// ---------------------------------------------------------------------------
// 5. Преобразование в ISO и обратно
// ---------------------------------------------------------------------------
group('Преобразование в ISO и обратно');
check('однозначная дата', partsToIso(parts(7, 11, 1994)), '1994-11-07');
check('двузначные день и месяц не теряются', partsToIso(parts(9, 9, 1994)), '1994-09-09');
check('некорректная дата не превращается в мусор', partsToIso(parts(31, 2, 2001)), null);
check('разбор ISO', isoToParts('1994-11-07'), { day: '07', month: '11', year: '1994' });
check('разбор мусора не бросает', isoToParts('не дата'), { day: '', month: '', year: '' });
check('null не бросает', isoToParts(null), { day: '', month: '', year: '' });

// ---------------------------------------------------------------------------

console.log('');
if (failed === 0) {
  console.log(`все ${total} проверок пройдены`);
} else {
  console.log(`провалено: ${failed} из ${total}`);
  process.exit(1);
}
