-- «Вернуть» после скипа: разрешаем отменить собственный скип
--
-- Зачем:
--
-- 1. На public.matches нет DELETE-политики. При включённом RLS это означает,
--    что delete() от имени authenticated отбрасывается молча: affected rows = 0,
--    ошибки нет. Обработчик «Вернуть» в Feed.tsx не проверял результат, поэтому
--    анкета возвращалась в ленту, а запись в matches оставалась со статусом
--    'rejected'. Человек продолжал числиться «отклонённым» и никогда не
--    появлялся снова ни в ленте, ни во вкладке «Все».
--
-- 2. Даже будь политика, удалять запись безусловно нельзя. Пока человек
--    «пропущен», он может успеть поставить лайк в ответ: likeProfile()
--    переводит пару в 'pending'. Безусловный delete() стёр бы его лайк.
--
-- Поэтому политика разрешает удаление ровно в двух случаях:
--   * запись моя (user_a = auth.uid()), то есть скип сделал я, а не он;
--   * статус всё ещё 'rejected', то есть её никто не перекрыл лайком.
--
-- Условие про статус делает всю защиту на уровне базы: клиент не сможет
-- удалить чужой лайк, даже если отправить специально составленный запрос.
--
-- Идемпотентно.

BEGIN;

DROP POLICY IF EXISTS "Отмена своего скипа" ON public.matches;

CREATE POLICY "Отмена своего скипа"
  ON public.matches
  FOR DELETE
  TO authenticated
  USING (auth.uid() = user_a AND status = 'rejected');

COMMENT ON POLICY "Отмена своего скипа" ON public.matches IS
  'Позволяет отменить собственный скип ("Вернуть" в ленте). Нельзя удалить '
  'пару, если её статус уже перекрыт лайком собеседника: тогда удаление '
  'уничтожило бы его лайк.';

COMMIT;
